"""Regenerate theme/css/pygments.css (syntax highlighting, light + dark).

Usage, from the repository root:

    ./venv/bin/python theme/tools/build_pygments_css.py

Light palette: GitHub's light syntax colours, written as a Pygments style
below (Pygments ships no GitHub light style). Dark palette: Pygments'
built-in "github-dark". The script checks the contrast of every token
colour against the code background (--code-bg in sibils.css): if one is
below 4.5:1, it lists the failing tokens and exits with an error without
writing the file, so a palette change cannot silently break WCAG AA.
"""

from __future__ import annotations

import pathlib
import re
import sys

from pygments.formatters import HtmlFormatter
from pygments.style import Style
from pygments.styles import get_style_by_name
from pygments.token import (
    Comment, Error, Generic, Keyword, Literal, Name, Number, Operator, String, Text, Token,
)

OUT = pathlib.Path(__file__).resolve().parent.parent / "css" / "pygments.css"
LIGHT_BG = "#f6f8fa"   # --code-bg, light
DARK_BG = "#161b22"    # --code-bg, dark
DARK_STYLE = "github-dark"

INK, COMMENT, RED, BLUE, NAVY, PURPLE, ORANGE, GREEN, DANGER = (
    "#1f2937", "#59636e", "#cf222e", "#0550ae", "#0a3069", "#6639ba", "#953800", "#116329",
    "#82071e",
)


class SibilsLight(Style):
    """GitHub light syntax colours, mapped like Pygments' github-dark."""

    name = "sibils-light"
    background_color = LIGHT_BG
    highlight_color = "#fff8c5"
    styles = {
        Token: INK,
        Error: DANGER,
        Keyword: RED,
        Keyword.Constant: BLUE,
        Keyword.Pseudo: BLUE,
        Name: INK,
        Name.Class: "bold " + ORANGE,
        Name.Constant: "bold " + BLUE,
        Name.Decorator: "bold " + PURPLE,
        Name.Entity: ORANGE,
        Name.Exception: "bold " + ORANGE,
        Name.Function: "bold " + PURPLE,
        Name.Label: "bold " + BLUE,
        Name.Namespace: RED,
        Name.Property: BLUE,
        Name.Tag: GREEN,
        Name.Variable: ORANGE,
        Literal: NAVY,
        Literal.Date: BLUE,
        String: NAVY,
        String.Affix: BLUE,
        String.Delimiter: BLUE,
        String.Escape: BLUE,
        String.Heredoc: BLUE,
        String.Regex: BLUE,
        Number: BLUE,
        Comment: "italic " + COMMENT,
        Comment.Preproc: "bold " + COMMENT,
        Comment.Special: "bold italic " + COMMENT,
        Operator: "bold " + RED,
        Generic: INK,
        Generic.Deleted: f"bg:#ffebe9 {DANGER}",
        Generic.Emph: "italic",
        Generic.Error: DANGER,
        Generic.Heading: "bold " + BLUE,
        Generic.Inserted: f"bg:#dafbe1 {GREEN}",
        Generic.Output: COMMENT,
        Generic.Prompt: COMMENT,
        Generic.Strong: "bold",
        Generic.EmphStrong: "bold italic",
        Generic.Subheading: BLUE,
        Generic.Traceback: RED,
        Generic.Underline: "underline",
        Text.Whitespace: COMMENT,
    }


def _lum(hex_colour: str) -> float:
    h = hex_colour.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    rgb = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a: str, b: str) -> float:
    la, lb = sorted((_lum(a), _lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def check(style, background: str, label: str) -> list[str]:
    errors = []
    for token, st in style.list_styles():
        if not st["color"] or token in Text.Whitespace:
            continue
        bg = "#" + st["bgcolor"] if st["bgcolor"] else background
        ratio = contrast("#" + st["color"], bg)
        if ratio < 4.5:
            errors.append(f"{label}: {token} #{st['color']} on {bg} = {ratio:.2f}")
    return errors


def rules(style, prefix: str) -> list[str]:
    """Token rules only: drop the unscoped pre/linenos rules and the background."""
    css = HtmlFormatter(style=style).get_style_defs(prefix)
    out = []
    for line in css.splitlines():
        if not line.startswith(prefix):
            continue
        if re.match(re.escape(prefix) + r" (\{|\.hll )", line):
            continue  # background and highlighted lines: sibils.css (--code-bg, --hll-bg)
        out.append(line)
    return out


def main() -> int:
    dark = get_style_by_name(DARK_STYLE)
    errors = check(SibilsLight, LIGHT_BG, "light") + check(dark, DARK_BG, "dark")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    parts = [
        "/* Generated by theme/tools/build_pygments_css.py: do not edit by hand. */",
        "/* Light: GitHub light colours. Every token is >= 4.5:1 on " + LIGHT_BG + ". */",
        *rules(SibilsLight, ".highlight"),
        "",
        f"/* Dark: Pygments '{DARK_STYLE}'. Every token is >= 4.5:1 on {DARK_BG}.",
        "   Screen only: print always uses the light colours. */",
        "@media screen {",
        *("  " + r for r in rules(dark, '[data-theme="dark"] .highlight')),
        "}",
        "",
        "/* Dark, without JavaScript (no data-theme attribute): follow the system. */",
        "@media screen and (prefers-color-scheme: dark) {",
        *("  " + r for r in rules(dark, ":root:not([data-theme]) .highlight")),
        "}",
        "",
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
